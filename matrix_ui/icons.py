PALETTE = {
    'Y': (255, 220, 0),
    'W': (220, 220, 220),
    'G': (150, 150, 150),  # Gray for clouds/fog
    'B': (80, 140, 255),
    'R': (255, 60, 60),
}


def get_icon_for_code(weather_code):
    if weather_code == 0:
        return SUN
    elif weather_code == 1:
        return PARTLY_CLOUDY
    elif weather_code in [2, 3]:
        return CLOUD
    elif weather_code in [45, 48]:
        return FOG
    elif weather_code in [51, 53, 55, 56, 57, 61, 63, 65, 66, 67, 80, 81, 82]:
        return RAIN
    elif weather_code in [71, 73, 75, 77, 85, 86]:
        return SNOW
    elif weather_code in [95, 96, 99]:
        return STORM
    else:
        return UNKNOWN


ICONS = {
    "sun": SUN, "cloud": CLOUD, "rain": RAIN, "snow": SNOW, "storm": STORM,
    "fog": FOG, "unknown": UNKNOWN, "partly_cloudy": PARTLY_CLOUDY,
}


def draw_icon(canvas, icon, x_offset, y_offset):
    for row_idx, row in enumerate(icon):
        for col_idx, color_key in enumerate(row):
            if color_key is None:
                continue
            r, g, b = PALETTE[color_key]
            canvas.SetPixel(x_offset + col_idx, y_offset + row_idx, r, g, b)
